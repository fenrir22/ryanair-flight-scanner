// Funzione per tradurre un nome
export function translateName(name: string): string {
  return airportTranslations[name] || name
}

// Funzione per tradurre un aeroporto completo
export function translateAirport(code: string, name: string, cityName: string): { name: string; cityName: string } {
  const translatedName = airportTranslations[code] || airportTranslations[name] || name
  const translatedCity = airportTranslations[cityName] || cityName
  
  return {
    name: translatedName,
    cityName: translatedCity
  }
}
